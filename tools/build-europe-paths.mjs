// Generates src/data/europe-geo.json: SVG paths for European countries (and a
// clipped background of neighbouring land), projected for a Europe map.
//
// Source geometry: the `world-atlas` package (ISC license), built from Natural
// Earth admin-0 countries (public domain). The coarse 1:110m layer is used for
// size; small countries missing from it (e.g. Malta) come from the 1:50m layer.
// Coordinates are rounded to keep the file small; the map is for orientation,
// not an authoritative boundary source.
//
// The dependencies are deliberately NOT in package.json. To regenerate:
//   npm install --no-save world-atlas@2 topojson-client@3 d3-geo@3
//   node tools/build-europe-paths.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { feature } from 'topojson-client';
import { geoAzimuthalEqualArea, geoPath } from 'd3-geo';

const require = createRequire(import.meta.url);
const load = (file) => {
  const topo = JSON.parse(readFileSync(require.resolve(`world-atlas/${file}`), 'utf8'));
  return feature(topo, topo.objects.countries).features;
};
const coarse = load('countries-110m.json');
const fine = load('countries-50m.json');

const W = 600;
const H = 560;
// Rough Europe frame: Iceland to the Urals' western edge, North Africa to Lapland.
const frame = {
  type: 'Polygon',
  // Clockwise ring: d3-geo reads spherical polygons this way round.
  coordinates: [[[-24, 34], [-24, 71], [44, 71], [44, 34], [-24, 34]]],
};
const projection = geoAzimuthalEqualArea().rotate([-12, -52]).fitExtent([[6, 6], [W - 6, H - 6]], frame).clipExtent([[0, 0], [W, H]]);
const path = geoPath(projection);

// ISO 3166 numeric -> alpha-2 for the countries treated as European here.
const EU = {
  '040': 'AT', '056': 'BE', '100': 'BG', '191': 'HR', '196': 'CY', '203': 'CZ', '208': 'DK', '233': 'EE', '246': 'FI',
  '250': 'FR', '276': 'DE', '300': 'GR', '348': 'HU', '372': 'IE', '380': 'IT', '428': 'LV', '440': 'LT', '442': 'LU',
  '470': 'MT', '528': 'NL', '616': 'PL', '620': 'PT', '642': 'RO', '703': 'SK', '705': 'SI', '724': 'ES', '752': 'SE',
};
const OTHER_EUROPE = {
  '826': 'GB', '578': 'NO', '756': 'CH', '352': 'IS', '804': 'UA', '112': 'BY', '498': 'MD', '688': 'RS', '070': 'BA',
  '499': 'ME', '807': 'MK', '008': 'AL', '792': 'TR', '643': 'RU', '268': 'GE', '051': 'AM', '031': 'AZ', '020': 'AD',
  '492': 'MC', '438': 'LI', '674': 'SM', '336': 'VA',
};
const BY_NAME = { Kosovo: 'XK' };

const round = (d) => d.replace(/-?\d+\.\d+/g, (n) => (Math.round(parseFloat(n) * 10) / 10).toString());
// Keep only shapes that actually show inside the frame (not slivers on its edge).
// Tracked (European) countries are kept however small, e.g. Luxembourg or Malta.
const visible = (f, minArea) => {
  const [[x0, y0], [x1, y1]] = path.bounds(f);
  if (![x0, y0, x1, y1].every(Number.isFinite)) return false;
  return (x1 - x0) * (y1 - y0) >= minArea && x1 > 0 && y1 > 0 && x0 < W && y0 < H;
};

const countries = {};
const background = [];
const codeOf = (f) => {
  const id = String(f.id ?? '').padStart(3, '0');
  return EU[id] || OTHER_EUROPE[id] || BY_NAME[f.properties.name];
};
const coarseCodes = new Set(coarse.map(codeOf).filter(Boolean));
// Coarse shapes for everything, plus fine shapes for European countries the
// coarse layer leaves out.
const features = [...coarse, ...fine.filter((f) => codeOf(f) && !coarseCodes.has(codeOf(f)))];
for (const f of features) {
  const code = codeOf(f);
  if (!visible(f, code ? 0 : 4)) continue; // outside the frame, or a sliver of background
  const d = path(f);
  if (!d) continue;
  if (!code) {
    background.push(round(d));
    continue;
  }
  const [[x0, y0], [x1, y1]] = path.bounds(f);
  const [cx, cy] = path.centroid(f);
  countries[code] = {
    name: f.properties.name,
    eu: Object.values(EU).includes(code),
    d: round(d),
    label: [Math.round(cx), Math.round(cy)],
    area: Math.round((x1 - x0) * (y1 - y0)),
  };
}

// Label anchors that read better than the clipped centroid.
const NUDGE = { NO: [-40, 40], SE: [-6, 20], FI: [0, 20], RU: [-120, 60], GB: [6, 10], HR: [-8, -6], GR: [-6, -10] };
for (const [code, [dx, dy]] of Object.entries(NUDGE)) {
  if (countries[code]) countries[code].label = [countries[code].label[0] + dx, countries[code].label[1] + dy];
}

writeFileSync(
  new URL('../src/data/europe-geo.json', import.meta.url),
  JSON.stringify({
    source: 'world-atlas countries-50m (Natural Earth 1:50m admin-0, public domain), simplified; generated by tools/build-europe-paths.mjs',
    viewBox: `0 0 ${W} ${H}`,
    countries,
    background,
  }),
);
console.log(`Wrote ${Object.keys(countries).length} European countries and ${background.length} background shapes`);
