// Generates src/data/us-states-geo.json: one SVG path per state (plus D.C.),
// pre-projected to a 975x610 canvas, with a label anchor for each state.
//
// Source geometry: the `us-atlas` package (ISC license), built from the U.S.
// Census Bureau's cartographic boundary files (public domain). Its
// states-albers-10m.json is already projected with an Albers USA projection,
// so no projection step is needed here.
//
// The dependencies are deliberately NOT in package.json, so the app's
// lockfile stays untouched. To regenerate:
//   npm install --no-save us-atlas@3 topojson-client@3 d3-geo@3
//   node tools/build-state-paths.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { feature } from 'topojson-client';
import { geoPath } from 'd3-geo';

const require = createRequire(import.meta.url);
const topo = JSON.parse(readFileSync(require.resolve('us-atlas/states-albers-10m.json'), 'utf8'));

// FIPS code -> postal abbreviation
const FIPS = {
  '01': 'AL', '02': 'AK', '04': 'AZ', '05': 'AR', '06': 'CA', '08': 'CO', '09': 'CT', '10': 'DE',
  '11': 'DC', '12': 'FL', '13': 'GA', '15': 'HI', '16': 'ID', '17': 'IL', '18': 'IN', '19': 'IA',
  '20': 'KS', '21': 'KY', '22': 'LA', '23': 'ME', '24': 'MD', '25': 'MA', '26': 'MI', '27': 'MN',
  '28': 'MS', '29': 'MO', '30': 'MT', '31': 'NE', '32': 'NV', '33': 'NH', '34': 'NJ', '35': 'NM',
  '36': 'NY', '37': 'NC', '38': 'ND', '39': 'OH', '40': 'OK', '41': 'OR', '42': 'PA', '44': 'RI',
  '45': 'SC', '46': 'SD', '47': 'TN', '48': 'TX', '49': 'UT', '50': 'VT', '51': 'VA', '53': 'WA',
  '54': 'WV', '55': 'WI', '56': 'WY',
};

// Label anchors that read better than the geometric centroid.
const LABEL_NUDGE = { FL: [12, 6], LA: [-8, 0], MI: [10, 18], KY: [4, 2], ID: [0, 18], HI: [6, 6], AK: [0, 0] };

// Round coordinates to 1 decimal place to keep the file small.
const round = (d) => d.replace(/-?\d+\.\d+/g, (n) => (Math.round(parseFloat(n) * 10) / 10).toString());

const path = geoPath();
const states = {};
for (const f of feature(topo, topo.objects.states).features) {
  const abbr = FIPS[f.id];
  if (!abbr) continue;
  const [cx, cy] = path.centroid(f);
  const [dx, dy] = LABEL_NUDGE[abbr] || [0, 0];
  const [[x0, y0], [x1, y1]] = path.bounds(f);
  states[abbr] = {
    name: f.properties.name,
    d: round(path(f)),
    label: [Math.round(cx + dx), Math.round(cy + dy)],
    area: Math.round((x1 - x0) * (y1 - y0)),
  };
}

const out = {
  source: 'us-atlas states-albers-10m (U.S. Census Bureau cartographic boundaries, public domain); generated by tools/build-state-paths.mjs',
  viewBox: '0 0 975 610',
  states,
};
writeFileSync(new URL('../src/data/us-states-geo.json', import.meta.url), JSON.stringify(out));
console.log(`Wrote ${Object.keys(states).length} states`);
